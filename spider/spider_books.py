def fetch_baike_book(book: dict) -> dict:
    """从百度百科爬取著作详细信息"""
    url = book.get("url", "")
    result = dict(book)
    result.pop("url", None)

    if not url:
        return result

    try:
        resp = requests.get(url, headers=HEADERS, timeout=15)
        resp.encoding = "utf-8"
        soup = BeautifulSoup(resp.text, "lxml")

        # 提取在线摘要（作为补充）
        for cls in [re.compile(r"lemmaAbstract"), re.compile(r"para-oRcKc")]:
            div = soup.find("div", class_=cls)
            if div:
                text = div.get_text(strip=True)[:400]
                if len(text) > 80:
                    result["百科摘要"] = text
                break

        print(f"  ✓ 《{book['书名']}》爬取成功")

    except Exception as e:
        print(f"  ⚠ 《{book['书名']}》爬取失败（使用预设数据）：{e}")

    return result


